def generate_github_pdf(gh_data: dict, audit: dict) -> bytes:
    """
    Generate a styled PDF for the GitHub Profile Analyzer results.

    Args:
        gh_data: The dict from fetch_complete_github_data()
        audit:   The dict from audit_github_profile()
    Returns:
        bytes -- the raw PDF binary ready for st.download_button
    """
    profile = gh_data["profile"]
    stats   = gh_data["stats"]
    score   = audit["total_score"]
    grade   = audit["grade"]
    dims    = audit["dimensions"]

    p_name  = _clean(profile.get("name") or profile.get("login", "Unknown"))
    p_login = _clean(profile.get("login", "unknown"))

    pdf = _DevPilotPDF(f"GitHub Portfolio Audit -- @{p_login}")
    pdf.add_page()

    # Cover
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(*_Color.BG_DARK)
    pdf.cell(0, 10, "", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*_Color.GRAY_500)
    pdf.cell(0, 6, f"./",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    if profile.get("bio"):
        pdf.caption(profile["bio"])
    pdf.ln(3)

    pdf.score_badge(score, label=_clean(grade))
    pdf.ln(4)

    # Profile Stats
    pdf.section_title("Profile Overview")
    stat_rows = [
        ("Original Repositories",  str(stats["original_repo_count"])),
        ("Total Stars Earned",      str(stats["total_stars"])),
        ("Total Forks",             str(stats["total_forks"])),
        ("Repos with Description",  f"{stats['repos_with_description']} / {stats['original_repo_count']}"),
        ("Repos with License",      str(stats.get("repos_with_license", 0))),
        ("Repos with Live Demo",    str(stats.get("repos_with_homepage", 0))),
        ("Followers",               str(profile.get("followers", 0))),
        ("Location",                _clean(profile.get("location") or "--")),
    ]
    for label, val in stat_rows:
        pdf.set_font("Helvetica", "", 9.5)
        pdf.set_text_color(*_Color.GRAY_700)
        pdf.cell(90, 6, _clean(label) + ":", new_x=XPos.RIGHT, new_y=YPos.TOP)
        pdf.set_font("Helvetica", "B", 9.5)
        pdf.set_text_color(*_Color.BG_DARK)
        pdf.cell(80, 6, _clean(val), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(2)

    # Score Breakdown
    pdf.section_title("Portfolio Score Breakdown")
    for dim in dims.values():
        pdf.progress_bar(dim["label"], dim["score"], dim["max"])
    pdf.ln(2)

    # Recruiter Verdict
    pdf.section_title("Recruiter Verdict")
    pdf.body(audit.get("verdict", ""))
    pdf.ln(2)

    # Green Flags / Red Flags
    if audit.get("green_flags"):
        pdf.section_title("Green Flags")
        for gf in audit["green_flags"]:
            pdf.bullet_item(gf, color=_Color.GREEN, prefix="+")
        pdf.ln(2)

    if audit.get("red_flags"):
        pdf.section_title("Red Flags")
        for rf in audit["red_flags"]:
            pdf.bullet_item(rf, color=_Color.RED, prefix="!")
        pdf.ln(2)

    # Dimension Details
    pdf.section_title("Dimension-Level Strengths and Gaps")
    for dim in dims.values():
        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(*_Color.INDIGO)
        pdf.cell(0, 6, _clean(f"{dim['label']}  ({dim['score']}/{dim['max']})"),
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        for s in dim.get("strengths", []):
            pdf.bullet_item(s, color=_Color.GREEN, prefix="+")
        for imp in dim.get("improvements", []):
            pdf.bullet_item(imp, color=_Color.RED, prefix="!")
        pdf.ln(1)
    pdf.ln(2)

    # Action Plan
    if pdf.get_y() > 40:
        pdf.add_page()
    pdf.section_title("Prioritized Action Plan")
    pdf.caption("Ranked checklist to rapidly increase your developer portfolio readiness score.")
    pdf.ln(2)

    for i, act in enumerate(audit.get("action_checklist", []), 1):
        impact = act.get("impact", "Medium")
        effort = act.get("effort", "Low")
        color = _Color.RED if impact == "High" else _Color.ORANGE if impact == "Medium" else _Color.GREEN
        bx, by = pdf.get_x(), pdf.get_y()

        pdf.set_fill_color(245, 245, 252)
        pdf.rect(bx, by, 174, 12, style="F")
        pdf.set_fill_color(*color)
        pdf.rect(bx, by, 2, 12, style="F")

        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(*_Color.BG_DARK)
        pdf.set_xy(bx + 5, by + 2)
        pdf.cell(120, 5, _clean(f"{i}. {act['task']}"),
                 new_x=XPos.RIGHT, new_y=YPos.TOP)

        pdf.set_font("Helvetica", "", 8)
        pdf.set_text_color(*_Color.GRAY_500)
        pdf.set_xy(bx + 128, by + 2)
        pdf.cell(44, 5, f"{impact} Impact  |  {_clean(effort)}", align="R",
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        pdf.set_xy(bx, by + 14)

    pdf.ln(3)

    # Repository Health Audit
    repo_audits = audit.get("repo_audits", [])
    if repo_audits:
        pdf.section_title("Repository Health Audit")
        pdf.caption(f"Audited {len(repo_audits)} original repositories for documentation and hygiene standards.")
        pdf.ln(2)

        for r in repo_audits[:20]:
            if pdf.get_y() > 260:
                pdf.add_page()

            bx, by = pdf.get_x(), pdf.get_y()
            hs = r.get("health_score", 0)
            bar_color = _Color.GREEN if hs >= 70 else _Color.YELLOW if hs >= 40 else _Color.RED

            pdf.set_fill_color(245, 245, 252)
            pdf.rect(bx, by, 174, 14, style="F")

            pdf.set_font("Helvetica", "B", 9.5)
            pdf.set_text_color(*_Color.INDIGO)
            pdf.set_xy(bx + 3, by + 2)
            pdf.cell(110, 5, _clean(r["name"]), new_x=XPos.RIGHT, new_y=YPos.TOP)

            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(*bar_color)
            pdf.set_xy(bx + 118, by + 2)
            pdf.cell(50, 5, f"Health: {hs}/100  Stars: {r.get('stars', 0)}",
                     align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            badges = []
            if r.get("has_description"):  badges.append("[+] Description")
            else:                         badges.append("[ ] No Desc")
            if r.get("has_license"):      badges.append("[+] License")
            else:                         badges.append("[ ] No License")
            if r.get("has_homepage"):     badges.append("[+] Live Demo")
            else:                         badges.append("[ ] No Demo")
            if r.get("has_topics"):       badges.append("[+] Topics")
            else:                         badges.append("[ ] No Topics")

            pdf.set_font("Helvetica", "", 7.5)
            pdf.set_text_color(*_Color.GRAY_500)
            pdf.set_xy(bx + 3, by + 8)
            pdf.cell(0, 4.5, "   ".join(badges), new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            pdf.set_xy(bx, by + 16)

    # Language Distribution
    lang_bytes = gh_data.get("language_bytes", {})
    if lang_bytes:
        if pdf.get_y() > 40:
            pdf.add_page()
        pdf.section_title("Language Distribution")
        total_bytes = sum(lang_bytes.values())
        sorted_langs = sorted(lang_bytes.items(), key=lambda x: x[1], reverse=True)
        for lang, b_count in sorted_langs[:10]:
            pct = (b_count / total_bytes) * 100
            pdf.progress_bar(_clean(lang), round(pct), 100)
        pdf.ln(2)

    return bytes(pdf.output())


