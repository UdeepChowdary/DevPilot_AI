"""
PDF Report Generator -- DevPilot AI
Generates professionally styled PDF reports for the Resume Analyzer and GitHub Profile Analyzer.
Uses fpdf2 (pure Python, no headless browser or system dependencies required).

NOTE: fpdf2's built-in Helvetica font is Latin-1 only.
All strings passed to PDF cells must be ASCII/Latin-1 safe.
The _clean() helper handles this transparently.
"""

import re
from fpdf import FPDF
from fpdf.enums import XPos, YPos
from datetime import datetime
from typing import Any


# ---------------------------------------------------------------------------
# Latin-1 Safety Helper
# ---------------------------------------------------------------------------

_EMOJI_RE = re.compile(
    "["
    "\U00010000-\U0010FFFF"
    "\U0001F000-\U0001FFFF"
    "\u2600-\u27BF"
    "\u2300-\u23FF"
    "\u2700-\u27BF"
    "\u2B00-\u2BFF"
    "\u2500-\u257F"   # box-drawing
    "\u2580-\u259F"   # block elements
    "]",
    flags=re.UNICODE,
)


def _clean(text: str) -> str:
    """
    Strip emoji and any characters outside Latin-1 (0x00-0xFF).
    fpdf2's built-in Helvetica font only supports Latin-1 encoding.
    """
    text = _EMOJI_RE.sub("", str(text))
    return text.encode("latin-1", errors="ignore").decode("latin-1")


# ---------------------------------------------------------------------------
# Shared Design Tokens
# ---------------------------------------------------------------------------

class _Color:
    BG_DARK  = (15,  12,  41)
    INDIGO   = (99,  102, 241)
    WHITE    = (255, 255, 255)
    GRAY_900 = (15,  23,  42)
    GRAY_700 = (51,  65,  85)
    GRAY_500 = (100, 116, 139)
    GRAY_300 = (148, 163, 184)
    GREEN    = (34,  197, 94)
    YELLOW   = (234, 179, 8)
    RED      = (239, 68,  68)
    ORANGE   = (249, 115, 22)


# ---------------------------------------------------------------------------
# Base PDF Class
# ---------------------------------------------------------------------------

class _DevPilotPDF(FPDF):
    """Base PDF with DevPilot branding, header, footer, and helper methods."""

    def __init__(self, title: str):
        super().__init__()
        self.title_text = _clean(title)
        self.set_auto_page_break(auto=True, margin=18)
        self.set_margins(18, 18, 18)

    def header(self):
        # Dark hero bar
        self.set_fill_color(*_Color.BG_DARK)
        self.rect(0, 0, 210, 26, style="F")

        # Brand name
        self.set_font("Helvetica", "B", 13)
        self.set_text_color(*_Color.WHITE)
        self.set_xy(10, 7)
        self.cell(0, 10, "DevPilot AI", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        # Title tag (right-aligned)
        self.set_font("Helvetica", "", 9)
        self.set_text_color(*_Color.GRAY_300)
        self.set_xy(10, 16)
        self.cell(0, 6, self.title_text, align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        # Indigo accent line
        self.set_draw_color(*_Color.INDIGO)
        self.set_line_width(0.8)
        self.line(0, 26, 210, 26)
        self.set_line_width(0.2)
        self.ln(6)

    def footer(self):
        self.set_y(-14)
        self.set_draw_color(*_Color.GRAY_700)
        self.set_line_width(0.3)
        self.line(18, self.get_y(), 192, self.get_y())
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*_Color.GRAY_500)
        ts = datetime.now().strftime("%B %d, %Y")
        self.cell(0, 8, f"Generated by DevPilot AI  |  {ts}  |  Page {self.page_no()}", align="C")

    # -- Helpers ------------------------------------------------------------

    def section_title(self, text: str):
        """Bold indigo section heading with underline accent."""
        self.set_font("Helvetica", "B", 12)
        self.set_text_color(*_Color.INDIGO)
        self.cell(0, 8, _clean(text), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        # Accent line
        self.set_draw_color(*_Color.INDIGO)
        self.set_line_width(0.5)
        x = self.get_x()
        y = self.get_y()
        self.line(x, y, x + 174, y)
        self.set_line_width(0.2)
        self.ln(3)
        self.set_text_color(*_Color.GRAY_900)

    def body(self, text: str, bold: bool = False):
        """Standard body text that auto-wraps."""
        self.set_font("Helvetica", "B" if bold else "", 10)
        self.set_text_color(*_Color.GRAY_900)
        self.multi_cell(0, 6, _clean(text), new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    def caption(self, text: str):
        self.set_font("Helvetica", "I", 8.5)
        self.set_text_color(*_Color.GRAY_500)
        self.multi_cell(0, 5, _clean(text), new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    def bullet_item(self, text: str, color: tuple = _Color.GRAY_700, prefix: str = "-"):
        self.set_font("Helvetica", "", 9.5)
        self.set_text_color(*color)
        self.set_x(self.get_x() + 4)
        self.multi_cell(0, 6, f"{prefix}  {_clean(text)}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_text_color(*_Color.GRAY_900)

    def score_badge(self, score: int, max_score: int = 100, label: str = "Score"):
        """Colored score badge."""
        pct = score / max_score
        if pct >= 0.8:
            bg = _Color.GREEN
        elif pct >= 0.65:
            bg = _Color.YELLOW
        elif pct >= 0.45:
            bg = _Color.ORANGE
        else:
            bg = _Color.RED

        self.set_fill_color(*bg)
        self.set_text_color(*_Color.WHITE)
        self.set_font("Helvetica", "B", 28)
        bx = self.get_x()
        by = self.get_y()
        self.cell(52, 18, f"{score}", align="C", fill=True, new_x=XPos.RIGHT, new_y=YPos.TOP)

        self.set_font("Helvetica", "", 9)
        self.set_text_color(*_Color.GRAY_500)
        self.set_xy(bx + 56, by + 3)
        self.cell(0, 6, f"/ {max_score}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_xy(bx + 56, by + 9)
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(*_Color.GRAY_700)
        self.cell(0, 6, _clean(label), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        self.set_xy(bx, by + 22)

    def progress_bar(self, label: str, value: int, max_val: int, w: float = 160):
        """Horizontal labeled progress bar."""
        pct = value / max_val if max_val else 0
        if pct >= 0.75:
            bar_color = _Color.GREEN
        elif pct >= 0.5:
            bar_color = _Color.YELLOW
        else:
            bar_color = _Color.RED

        bx, by = self.get_x(), self.get_y()

        # Label
        self.set_font("Helvetica", "", 9)
        self.set_text_color(*_Color.GRAY_700)
        self.set_xy(bx, by)
        self.cell(120, 6, _clean(label), new_x=XPos.RIGHT, new_y=YPos.TOP)

        # Score text
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*_Color.INDIGO)
        self.set_xy(bx + 122, by)
        self.cell(38, 6, f"{value} / {max_val} ({round(pct*100)}%)", align="R",
                  new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        # Track
        self.set_fill_color(220, 220, 230)
        self.rect(bx, by + 7, w, 4, style="F")

        # Fill
        self.set_fill_color(*bar_color)
        self.rect(bx, by + 7, max(w * pct, 0), 4, style="F")

        self.set_xy(bx, by + 14)

    def kw_chip_row(self, keywords: list, chip_color: tuple, max_per_row: int = 6):
        """Render keywords as small inline chips."""
        if not keywords:
            return
        self.set_font("Helvetica", "", 7)
        for i, kw in enumerate(keywords):
            self.set_fill_color(*chip_color)
            self.set_text_color(*_Color.WHITE)
            # Draw the filled cell for the chip
            self.cell(26, 5.5, _clean(kw)[:14], align="C", fill=True, new_x=XPos.RIGHT, new_y=YPos.TOP)
            
            # Draw empty space for the gap between chips
            self.cell(4, 5.5, "", new_x=XPos.RIGHT, new_y=YPos.TOP)
            
            # Wrap to next line
            if (i + 1) % max_per_row == 0 or i == len(keywords) - 1:
                self.ln(7.5)

    def divider(self):
        self.set_draw_color(*_Color.GRAY_300)
        self.set_line_width(0.2)
        x = self.get_x()
        y = self.get_y() + 2
        self.line(x, y, x + 174, y)
        self.ln(5)


