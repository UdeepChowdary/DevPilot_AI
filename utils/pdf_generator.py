def generate_resume_pdf(results: dict) -> bytes:
    """
    Generate a styled PDF for the Resume Analyzer results.

    Args:
        results: The dict stored in st.session_state["resume_results"]
    Returns:
        bytes -- the raw PDF binary ready for st.download_button
    """
    ats     = results["ats"]
    kw      = results["kw"]
    bullets = results["bullets"]
    score   = ats["total"]
    fname   = results.get("filename", "Resume")

    pdf = _DevPilotPDF("Resume ATS Audit Report")
    pdf.add_page()

    # Cover / Summary
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(*_Color.BG_DARK)
    pdf.cell(0, 10, "", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*_Color.GRAY_500)
    pdf.cell(0, 6, f"()", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(3)

    # Score verdict
    if score >= 80:
        verdict = "Excellent -- Interview Ready"
    elif score >= 65:
        verdict = "Competitive -- Minor Tweaks Needed"
    elif score >= 45:
        verdict = "Needs Refinement"
    else:
        verdict = "Weak ATS Profile"

    pdf.score_badge(score, label=verdict)
    pdf.ln(4)

    # Score Breakdown
    pdf.section_title("")
    for b in ats["breakdown"]:
        pdf.progress_bar(_clean(b["label"]), b["score"], b["max"])
    pdf.ln(2)

    # Strengths
    pdf.section_title("")
    for s in ats.get("strengths", []):
        pdf.bullet_item(s, color=_Color.GREEN, prefix="+")
    pdf.ln(2)

    # Weaknesses
    pdf.section_title("")
    for w in ats.get("weaknesses", []):
        pdf.bullet_item(w, color=_Color.RED, prefix="!")
    pdf.ln(2)

    # Keywords
    pdf.section_title("Keyword Analysis")
    if kw.get("jd_keywords"):
        mr = round(kw.get("match_rate", 0) * 100)
        pdf.body(f"Match Rate: {mr}%  ({len(kw['matched'])} matched / {len(kw['missing'])} missing)")
        pdf.ln(1)
        if kw["matched"]:
            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(*_Color.GREEN)
            pdf.cell(0, 6, f"Matched ({len(kw['matched'])}):", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            pdf.kw_chip_row(kw["matched"], _Color.GREEN)
        if kw["missing"]:
            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(*_Color.RED)
            pdf.cell(0, 6, f"Missing from JD ({len(kw['missing'])}):", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            pdf.kw_chip_row(kw["missing"], _Color.RED)
    else:
        rk = kw.get("resume_keywords", [])
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(*_Color.INDIGO)
        pdf.cell(0, 6, f"Extracted Resume Keywords ({len(rk)}):", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.kw_chip_row(rk[:30], _Color.INDIGO)
    pdf.ln(2)

    # Bullet Suggestions
    if bullets:
        if pdf.get_y() > 40:
            pdf.add_page()
        pdf.section_title("Bullet Enhancements")
        pdf.caption("Original vs. AI-enhanced resume bullets using Google's XYZ formula.")
        pdf.ln(2)

        for i, b in enumerate(bullets[:15], 1):
            if pdf.get_y() > 250:
                pdf.add_page()

            bx, by = pdf.get_x(), pdf.get_y()
            card_h = 22 + (len(b["enhanced"]) // 80) * 6

            pdf.set_fill_color(245, 245, 252)
            pdf.rect(bx, by, 174, card_h, style="F")
            pdf.set_fill_color(*_Color.INDIGO)
            pdf.rect(bx, by, 2, card_h, style="F")

            # Number label
            pdf.set_font("Helvetica", "B", 8)
            pdf.set_text_color(*_Color.INDIGO)
            pdf.set_xy(bx + 4, by + 2)
            pdf.cell(0, 5, f"#{i}", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            # Original
            pdf.set_font("Helvetica", "", 8)
            pdf.set_text_color(*_Color.GRAY_500)
            pdf.set_xy(bx + 4, by + 8)
            pdf.cell(18, 4.5, "Before:", new_x=XPos.RIGHT, new_y=YPos.TOP)
            pdf.set_xy(bx + 22, by + 8)
            pdf.set_font("Helvetica", "I", 8.5)
            pdf.multi_cell(148, 4.5, _clean(b["original"])[:120],
                           new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            # Enhanced
            after_y = by + 15
            pdf.set_xy(bx + 4, after_y)
            pdf.set_font("Helvetica", "B", 8)
            pdf.set_text_color(*_Color.INDIGO)
            pdf.cell(18, 4.5, "After:", new_x=XPos.RIGHT, new_y=YPos.TOP)
            pdf.set_xy(bx + 22, after_y)
            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(*_Color.GRAY_900)
            pdf.multi_cell(148, 5, _clean(b["enhanced"])[:150],
                           new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            # Quantified tag
            if b.get("has_metric"):
                ty = pdf.get_y() + 1
                pdf.set_fill_color(*_Color.GREEN)
                pdf.rect(bx + 4, ty, 24, 4.5, style="F")
                pdf.set_font("Helvetica", "", 6.5)
                pdf.set_text_color(*_Color.WHITE)
                pdf.set_xy(bx + 5, ty - 0.5)
                pdf.cell(22, 4.5, "", new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            pdf.set_xy(bx, by + card_h + 3)

    # Tips page
    if pdf.get_y() > 40:
        pdf.add_page()
    pdf.section_title("")
    pdf.body('"Accomplished [X] as measured by [Y], by doing [Z]"', bold=True)
    pdf.ln(2)
    tips = [
        "Begin every bullet with a high-impact action verb (Engineered, Spearheaded, Architected, Optimized).",
        "Quantify results wherever possible: use %, latency ms, $ amounts, user counts, or request volume.",
        "Keep bullets to 1-2 lines maximum -- hiring managers spend 6-8 seconds per resume.",
        "Mirror keywords and technologies directly from the job description in your skills and bullets.",
        "Add a 'Projects' section if missing -- it's the single highest-impact section for fresh graduates.",
    ]
    for t in tips:
        pdf.bullet_item(t, color=_Color.GRAY_700)

    return bytes(pdf.output())


